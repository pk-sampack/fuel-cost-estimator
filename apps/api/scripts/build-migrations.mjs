import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const apiRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = join(apiRoot, 'db', 'migrations');
const outFile = join(apiRoot, 'src', 'db', 'migrations.generated.ts');

const files = readdirSync(migrationsDir)
  .filter((file) => file.endsWith('.sql'))
  .sort();

const entries = files.map((name) => {
  const body = readFileSync(join(migrationsDir, name), 'utf8');
  return `  { name: ${JSON.stringify(name)}, body: ${JSON.stringify(body)} },`;
});

const content = `// Generated by scripts/build-migrations.mjs - do not edit.\nexport const BUNDLED_MIGRATIONS: ReadonlyArray<{ name: string; body: string }> = [\n${entries.join('\n')}\n];\n`;

writeFileSync(outFile, content);
console.log(`bundled ${files.length} migration(s) into src/db/migrations.generated.ts`);
